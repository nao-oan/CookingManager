function match(name: string, rules: [string[], string][]): string | null {
  for (const [keywords, emoji] of rules) {
    if (keywords.some((keyword) => name.includes(keyword))) return emoji;
  }
  return null;
}

/** 食材名から絵文字を選ぶ */
export function ingredientThumbnail(name: string): string {
  return match(name, INGREDIENT_RULES) ?? FALLBACK.ingredient;
}

/**
 * 料理名から絵文字を選ぶ。
 * 料理名としての手がかりが無い場合は、食材名の規則で拾えることがある
 * （「鮭の塩焼き」→ 焼き、「肉じゃが」→ 煮 など）。
 */
export function recipeThumbnail(name: string): string {
  return match(name, RECIPE_RULES) ?? match(name, INGREDIENT_RULES) ?? FALLBACK.recipe;
}
